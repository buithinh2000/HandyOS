await page.locator("#staffRole").fill("Carpenter");
await page.locator("#staffRate").fill("50");
await page.locator("#addStaff").click();
assert.match(await page.locator("#screen").innerText(),/Alex/);
await page.locator('[data-page="jobs"]').click();
await page.locator("#newJob").click();
await page.locator("#contract").fill("11000");
await page.locator("#saveJob").click();
await page.locator("#expenseTitle").fill("Sample material");
await page.locator("#expenseAmount").fill("110");
await page.locator("#addExpense").click();
await page.locator("#workerName").selectOption("Alex");
assert.equal(await page.locator("#workRate").inputValue(),"50");
await page.locator("#workHours").fill("8");
await page.locator("#workRate").fill("50");
await page.locator("#addHours").click();
await page.locator("#payRef").fill("Deposit 1");
await page.locator("#payAmount").fill("2200");
await page.locator("#payBasis").selectOption("inc");
await page.locator("#payStatus").selectOption("received");
await page.locator("#addPayment").click();
assert.match(await page.locator("#screen").innerText(),/\$9,500\.00/);
await page.locator("#taxReservePct").fill("15");
await page.locator("#saveJob").click();
assert.match(await page.locator("#screen").innerText(),/Tax & Reserve Fund/);
assert.match(await page.locator("#screen").innerText(),/\$1,650\.00/);
assert.match(await page.locator("#screen").innerText(),/\$7,850\.00/);
const profitRecord=await page.evaluate(()=>JSON.parse(localStorage.getItem("handyos-workspace-v07")).jobs[0]);
assert.equal(profitRecord.taxReservePct,15);

await page.locator("#payRef").fill("No GST receipt");
await page.locator("#payAmount").fill("200");
await page.locator("#payBasis").selectOption("no_gst");
await page.locator("#payStatus").selectOption("received");
await page.locator("#addPayment").click();
const payments=await page.evaluate(()=>JSON.parse(localStorage.getItem("handyos-workspace-v07")).jobs[0].payments);
assert.equal(payments[1].gstBasis,"no_gst");
assert.equal(payments[1].amount,200);
assert.match(await page.locator("#screen").innerText(),/\$2,400\.00/);
await page.locator('[data-page="employees"]').click();
assert.match(await page.locator("#screen").innerText(),/Alex/);
await page.locator('[data-open="worker"]').first().click();
await page.locator("#wageAmount").fill("250");
await page.locator("#addWage").click();
assert.match(await page.locator("#screen").innerText(),/\$150\.00/);
await page.locator('[data-settle]').first().click();
assert.match(await page.locator("#screen").innerText(),/Saved payroll settlements/);
assert.match(await page.locator("#screen").innerText(),/Up to date/);
await page.locator('[data-period="month"]').click();
await page.locator('[data-settle]').first().click();
assert.equal(await page.locator('table').first().locator('tbody tr').count()>0,true);
await page.locator('[data-period="year"]').click();
await page.locator('[data-back="employees"]').click();
assert.equal(await page.locator("#wageYearFilter").count(),1);
const currentYear=(await page.evaluate(()=>new Date().getFullYear())).toString();
await page.locator("#wageYearFilter").selectOption(currentYear);
assert.match(await page.locator("#screen").innerText(),/Alex/);
await page.locator('[data-page="expenses"]').click();
