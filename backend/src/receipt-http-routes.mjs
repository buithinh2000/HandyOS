// HandyOS authenticated receipt HTTP route adapter (SOURCE-ONLY, NOT LIVE).
// The caller must verify a Cognito access token and resolve its active tenant/role
// from PostgreSQL, never from JSON/query/URL. No SDK, cloud credentials or direct S3.
import {HttpError,ensureUuid} from "./domain.mjs";

const paths=Object.freeze({
 begin:/^\/v1\/jobs\/([^/]+)\/receipts\/uploads$/,
 confirm:/^\/v1\/jobs\/([^/]+)\/receipts\/([^/]+)\/confirm$/,
 media:/^\/v1\/jobs\/([^/]+)\/receipts\/([^/]+)\/media$/
});
function safeBody(d){
 if(!d||typeof d!=="object"||Array.isArray(d))throw new HttpError(400,"Invalid receipt payload");
 const allowed=new Set(["boughtOn","storeReference","amountGross","gstBasis","notes","contentType","contentLength"]);
 if(Object.keys(d).some(k=>!allowed.has(k)))throw new HttpError(400,"Unexpected receipt fields");
 return d;
}
export function matchReceiptRoute(method,path){
 if(method==="POST"){
  let m=paths.begin.exec(path);
  if(m)return {kind:"begin",jobId:ensureUuid(m[1])};
  m=paths.confirm.exec(path);
  if(m)return {kind:"confirm",jobId:ensureUuid(m[1]),receiptId:ensureUuid(m[2])};
 }
 if(method==="GET"){
  const m=paths.media.exec(path);
  if(m)return {kind:"media",jobId:ensureUuid(m[1]),receiptId:ensureUuid(m[2])};
 }
 return null;
}
// identity is generated by API after token signature, issuer, expiry and tenant
// membership checks. This function intentionally cannot accept token claims
// directly from a request body or a caller-controlled role header.
export async function dispatchReceiptRoute({route,identity,workflow,readBody}){
 if(!route)return null;
 if(!identity||identity.verifiedByApi!==true||typeof identity.actorSub!=="string"||
  !/^[0-9a-f-]{36}$/i.test(identity.tenantId))throw new HttpError(401,"Verified Owner session required");
 if(!["owner","manager"].includes(identity.role))throw new HttpError(403,"Receipts are restricted to Owner/Manager");
 if(!workflow)throw new HttpError(503,"Private receipt storage is not configured");
 const auth=Object.freeze({verifiedByApi:true,actorSub:identity.actorSub,tenantId:identity.tenantId});
 try {
  if(route.kind==="begin"){
   if(typeof readBody!=="function")throw new HttpError(500,"Request reader missing");
   const details=safeBody(await readBody());
   return await workflow.beginUpload({auth,jobId:route.jobId,details});
  }
  if(route.kind==="confirm")
   return await workflow.confirmUpload({auth,jobId:route.jobId,receiptId:route.receiptId});
  if(route.kind==="media")
   return await workflow.viewReceipt({auth,jobId:route.jobId,receiptId:route.receiptId});
  throw new HttpError(404,"Receipt route unknown");
 }catch(err){
  if(err instanceof HttpError)throw err;
  // Never surface S3 object keys, signed URLs, SQL details or authorization
  // internals in HTTP responses. Errors stay closed and metadata-only.
  throw new HttpError(503,"Receipt operation unavailable; verify authorization and storage");
 }
}
